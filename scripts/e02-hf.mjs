// Builds the E02 "gate panel" HyperFrames clips (e02-pib, e02-lanes, e02-door) from one spec,
// so every chip shares the same look: a dark glass split-flap tile that flips down like a
// departure board, a Phosphor (MIT) icon tile, and a check badge that pops when the VO says it.
// Usage: node scripts/e02-hf.mjs   (then run hyperframes check/render in each folder)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = process.env.PHOSPHOR_DIR ?? "/tmp/claude-0/-home-user-motion-video/6b1e54bc-e4d3-57f4-ac75-a60c86325b65/scratchpad/phos/package/assets/fill";
const icon = (name) => readFileSync(join(ICONS, `${name}-fill.svg`), "utf8").replace(/<svg[^>]*>/, '<svg viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">').trim();

const CLIPS = {
  "e02-pib": {
    dur: 9, // beat 10–19 s
    left: 300, width: 700, top: 1448, gap: 136,
    chips: [
      { at: 2.68, icon: "coins", tag: "PAID", text: "Import duties & taxes", tone: "orange" },
      { at: 3.93, icon: "file-text", tag: "FILED", text: "Import declaration (PIB)", tone: "orange" },
    ],
    out: 8.55,
  },
  "e02-lanes": {
    dur: 9, // beat 19–28 s
    left: 300, width: 700, top: 1448, gap: 136,
    chips: [
      { at: 2.78, icon: "check-circle", tag: "GREEN", text: "Released, no physical check", tone: "green", ok: false },
      { at: 5.16, icon: "magnifying-glass", tag: "RED · GOODS & DOCUMENTS", text: "Inspected first", tone: "red", ok: false },
    ],
    out: 8.55,
  },
  "e02-door": {
    dur: 9, // beat 39–48 s
    left: 80, width: 920, top: 1296, gap: 142,
    chips: [
      { at: 2.22, icon: "files", tag: "CHECKED", text: "Documents", tone: "orange" },
      { at: 3.11, icon: "shield-check", tag: "HANDLED", text: "Clearance", tone: "orange" },
      { at: 4.45, icon: "truck", tag: "TRUCKED", text: "To your warehouse", tone: "orange" },
    ],
    out: 8.6,
  },
};

const TONES = {
  orange: ["#f26a1f", "#f5a623"],
  green: ["#1f9d55", "#5fd38d"],
  red: ["#c0392b", "#ff6b4a"],
};

for (const [id, c] of Object.entries(CLIPS)) {
  const chips = c.chips
    .map((ch, i) => {
      const [a, b] = TONES[ch.tone];
      return `      <div id="chip-${i}" class="chip clip" data-start="0" data-duration="${c.dur}" data-track-index="${i}" style="top:${c.top + i * c.gap}px; --a:${a}; --b:${b};">
        <div class="flap">
          <div class="ico">${icon(ch.icon)}</div>
          <div class="txt"><div class="tag">${ch.tag}</div><div class="main">${ch.text}</div></div>
          ${ch.ok === false ? "" : `<div class="ok">${icon("check-circle")}</div>`}
        </div>
      </div>`;
    })
    .join("\n");
  const anims = c.chips
    .map(
      (ch, i) => `      flip("#chip-${i} .flap", ${ch.at.toFixed(2)});
${ch.ok === false ? "" : `      tl.fromTo("#chip-${i} .ok", { scale: 0, rotation: -90 }, { scale: 1, rotation: 0, duration: 0.42, ease: "back.out(2.6)" }, ${(ch.at + 0.32).toFixed(2)});\n`}
      tl.fromTo("#chip-${i} .shine", { xPercent: -120 }, { xPercent: 260, duration: 0.7, ease: "power2.inOut" }, ${(ch.at + 0.25).toFixed(2)});`,
    )
    .join("\n");
  const html = `<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <!--
      ${id}: generated by scripts/e02-hf.mjs (edit the spec there, not this file).
      Gate panel chips, transparent WebM → remotion/public/hf/${id}.webm. Chip text repeats the VO wording only.
      Icons: Phosphor Icons 2.1.1 fill (MIT).
    -->
    <style>
      @font-face { font-family: "Plus Jakarta Sans"; src: url("assets/PlusJakartaSans-var.woff2") format("woff2"); font-weight: 200 800; }
      @font-face { font-family: "League Gothic"; src: url("assets/LeagueGothic-var.woff2") format("woff2"); font-weight: 400; }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1080px; height: 1920px; overflow: hidden; background: transparent; }
      #root { position: relative; width: 100%; height: 100%; font-family: "Plus Jakarta Sans", sans-serif; }
      .chip { position: absolute; left: ${c.left}px; width: ${c.width}px; height: 116px; perspective: 900px; }
      .flap { position: relative; width: 100%; height: 100%; display: flex; align-items: center; gap: 22px; padding: 0 26px 0 18px;
        border-radius: 22px; overflow: hidden; transform-origin: 50% 0%;
        background: linear-gradient(180deg, rgba(16, 26, 48, 0.9), rgba(8, 14, 30, 0.9));
        border: 1.5px solid rgba(255, 255, 255, 0.14); box-shadow: 0 18px 40px rgba(0, 0, 0, 0.45), inset 0 1px 0 rgba(255, 255, 255, 0.08); }
      .flap::before { content: ""; position: absolute; left: 0; top: 0; bottom: 0; width: 7px; background: linear-gradient(180deg, var(--a), var(--b)); }
      .ico { flex: none; width: 80px; height: 80px; border-radius: 18px; display: grid; place-items: center; color: #fff;
        background: linear-gradient(135deg, var(--a), var(--b)); box-shadow: 0 6px 18px rgba(0, 0, 0, 0.35); }
      .ico svg { width: 48px; height: 48px; }
      .txt { flex: 1; min-width: 0; }
      .tag { font-family: "League Gothic", sans-serif; font-size: 34px; letter-spacing: 0.12em; line-height: 1; color: var(--b); }
      .main { font-weight: 700; font-size: 35px; line-height: 1.15; color: #fff7ef; white-space: nowrap; }
      .ok { flex: none; width: 54px; height: 54px; color: var(--b); }
      .ok svg { width: 100%; height: 100%; }
      .shine { position: absolute; top: 0; bottom: 0; left: 0; width: 40%; background: linear-gradient(100deg, transparent, rgba(255, 255, 255, 0.16), transparent); pointer-events: none; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="${id}" data-start="0" data-duration="${c.dur}" data-width="1080" data-height="1920">
${chips.replace(/<\/div>\n        <\/div>\n      <\/div>/g, '</div>\n          <div class="shine" data-layout-ignore></div>\n        </div>\n      </div>')}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });
      // Split-flap: the tile flips down from its top hinge, overshoots and clacks to rest.
      const flip = (sel, at) => {
        tl.fromTo(sel, { rotationX: -100, opacity: 0, filter: "brightness(2)" }, { rotationX: 12, opacity: 1, filter: "brightness(1)", duration: 0.26, ease: "power3.in" }, at);
        tl.to(sel, { rotationX: -5, duration: 0.09, ease: "power1.out" }, at + 0.26);
        tl.to(sel, { rotationX: 0, duration: 0.14, ease: "power1.inOut" }, at + 0.35);
      };
${anims}
      // Out: the tiles drop away (the container is about to fall through the gate).
      tl.to(".flap", { y: 260, rotationX: 70, opacity: 0, duration: 0.32, ease: "power3.in", stagger: 0.05 }, ${c.out});
      window.__timelines["${id}"] = tl;
    </script>
  </body>
</html>
`;
  writeFileSync(new URL(`../hyperframes/${id}/index.html`, import.meta.url), html);
  console.log("wrote", id);
}
